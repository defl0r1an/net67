#: Тональная шкала акцента из фирменного файла. Построена в OKLCH на общей
#: шкале светлоты, поэтому одинаковые ступени разных ролей визуально равны.
# Нейтральная шкала: интерфейс чёрно-серо-белый, цветного акцента в нём
# нет. Ступени те же, что и у прежней бордовой: 500 — рабочий акцент,
# 400 — наведение, 700 — нажатие, 900 — фон иконки.
#
# 500 выбран средне-серым намеренно. qfluentwidgets держит один акцент на
# обе темы и сам двигает его: в тёмной осветляет и кладёт поверх тёмный
# текст, в светлой затемняет и кладёт светлый. Средняя ступень поэтому
# даёт почти белую кнопку на тёмном фоне и почти чёрную на светлом, а
# край шкалы дал бы белое на белом.
# Каналы держим равными. Стоило поставить 500 как #6e6e76 — синий канал
# на восемь единиц выше остальных, — и qfluentwidgets, осветляя акцент,
# растянул этот подтон в заметный лиловый налёт на белой кнопке.
# Сиреневая шкала Nora. Акцент приложения обязан совпадать с акцентом
# оболочки: правая часть собрана из виджетов qfluentwidgets, и они
# берут цвет не из моих стилей, а из своего themeColor. Пока здесь
# стоял серый, выделенный пункт слева был сиреневым, а кнопка справа —
# бирюзовой, и это было видно на каждом экране.
#
# 500 — рабочий акцент, соответствует --foreground-color-1 Nora
# (hsl 247 74% 65%). Тёмная тема qfluentwidgets осветляет его примерно
# до --dark-text-color-highlight-2 (hsl 244 98% 80%, #a19afe), которым
# залит выбранный пункт панели.
# Акцент серый по просьбе: «смени цвет акцента на серый». Каналы
# держим равными — неравные дают цветной налёт после того, как тёмная
# тема qfluentwidgets осветлит акцент. Это уже случалось: значение
# #6e6e76, где синий канал выше на восемь единиц, давало заметный
# лиловый оттенок на белой кнопке.
ACCENT_RAMP = {
    100: "#f2f2f2",
    200: "#e0e0e0",
    300: "#c6c6c6",
    400: "#a8a8a8",
    500: "#8c8c8c",
    600: "#707070",
    700: "#565656",
    800: "#3d3d3d",
    900: "#242424",
}

NEUTRAL_RAMP = {
    100: "#f5f5f5",
    200: "#e7e7e7",
    300: "#d4d4d4",
    400: "#b7b7b7",
    500: "#989898",
    600: "#7a7a7a",
    700: "#5d5d5d",
    800: "#424242",
    900: "#2b2b2b",
}

#: Базовые роли из фирменного файла.
COLOR_BG = "#f2f2f3"
COLOR_SURFACE = "#e9e9ea"
COLOR_TEXT = "#1d1f20"
COLOR_ACCENT = "#8c8c8c"
COLOR_ACCENT_2 = "#a8a8a8"


@dataclass(frozen=True, slots=True)
class BrandPalette:
    """Акцентные цвета. Остальные берутся из темы qfluentwidgets."""

    accent: str
    accent_hover: str
    accent_pressed: str
    on_accent: str

    success: str
    warning: str
    danger: str
    neutral: str


#: Тема light. Акцент нейтральный, hover/pressed — соседние ступени
#: шкалы, а не подкрученные на глаз значения.
PALETTE_LIGHT = BrandPalette(
    accent=COLOR_ACCENT,
    accent_hover=ACCENT_RAMP[500],
    accent_pressed=ACCENT_RAMP[700],
    on_accent=COLOR_BG,
    success=NEUTRAL_RAMP[700],
    warning=NEUTRAL_RAMP[600],
    danger=NEUTRAL_RAMP[900],
    neutral=NEUTRAL_RAMP[600],
)

#: Тема dark. Акцент поднят на ступень шкалы: на тёмном фоне середина
#: не добирает контраста.
PALETTE_DARK = BrandPalette(
    accent=ACCENT_RAMP[500],
    accent_hover=ACCENT_RAMP[400],
    accent_pressed=ACCENT_RAMP[600],
    on_accent=ACCENT_RAMP[900],
    success=NEUTRAL_RAMP[200],
    warning=NEUTRAL_RAMP[300],
    danger=NEUTRAL_RAMP[100],
    neutral=NEUTRAL_RAMP[400],
)

#: Совместимость: большая часть кода ждёт одну строку с акцентом.
ACCENT_COLOR = PALETTE_LIGHT.accent

#: Фон и цвет знака для иконки приложения — вариант «App icon — rounded mask»
#: из фирменного файла: тёмно-синий квадрат со скруглением 20% и знаком «67n».
ICON_BG = ACCENT_RAMP[900]
ICON_FG = COLOR_BG
ICON_RADIUS_RATIO = 0.20


def get_palette(*, dark: bool) -> BrandPalette:
    """Палитра под текущую тему."""
    return PALETTE_DARK if dark else PALETTE_LIGHT


