#: Замок на цикл «прочитать hosts — поправить копию — записать целиком».
#:
#: Код, пишущий hosts, собран в одном модуле, но по времени писателей
#: бывает двое сразу: при запуске очередь «hosts» освежает адреса в
#: блоке net67, а «одна кнопка» в ту же секунду переприменяет
#: сохранённый выбор из своего потока. Каждый читает файл, правит свою
#: копию и пишет её поверх — без замка выигрывает дописавший последним,
#: а правка второго молча пропадает.
#:
#: RLock, а не Lock: обновление при запуске держит замок и изнутри зовёт
#: apply_service_dns_selections, который берёт его снова. Замок только
#: внутри процесса — второго net67 не даёт запустить защита от
#: повторного запуска.
HOSTS_EDIT_LOCK = threading.RLock()


def _serialized_hosts_edit(method):
    @functools.wraps(method)
    def wrapper(*args, **kwargs):
        with HOSTS_EDIT_LOCK:
            return method(*args, **kwargs)

    return wrapper


def _get_hosts_path_from_env() -> Path:
    """
    Возвращает путь к hosts через переменные окружения, чтобы корректно работать
    когда Windows установлена не на C:.
    """
    sys_root = os.environ.get("SystemRoot") or os.environ.get("WINDIR")
    if sys_root:
        return Path(sys_root, "System32", "drivers", "etc", "hosts")
    return Path(r"C:\Windows\System32\drivers\etc\hosts")


def _hosts_path() -> Path:
    """Путь к файлу hosts. Вне Windows — временный, а не выдуманный.

    Раньше здесь на любой не-Windows стоял тот же литерал
    ``C:\\Windows\\System32\\drivers\\etc\\hosts``. На Linux это не путь,
    а имя файла из одного куска с обратными слэшами: каждый прогон
    тестов, который трогает hosts, создавал такой файл в текущей папке.
    В корне репозитория он и обнаружился — прямо перед выкладкой, среди
    неотслеживаемых файлов.
    """
    if os.name == "nt":
        return _get_hosts_path_from_env()

    import tempfile

    return Path(tempfile.gettempdir()) / "net67-hosts-not-windows"


HOSTS_PATH = _hosts_path()

_MANAGED_HOSTS_BEGIN = "# >>> net67:hosts managed begin >>>"
_MANAGED_HOSTS_END = "# <<< net67:hosts managed end <<<"
_MANAGED_HOSTS_NOTICE = "# Generated by net67. Do not edit this block manually."

# Маркеры прежней версии приложения. Записываем всегда новые, но при чтении
# и очистке обязаны узнавать и старые: иначе блок, добавленный до
# переименования, останется в системном hosts навсегда — найти и удалить
# его будет уже нечем.
_LEGACY_MANAGED_HOSTS_BEGIN = "# >>> zapretgui:hosts managed begin >>>"
_LEGACY_MANAGED_HOSTS_END = "# <<< zapretgui:hosts managed end <<<"


def _is_managed_block_begin(stripped: str) -> bool:
    return stripped in (_MANAGED_HOSTS_BEGIN, _LEGACY_MANAGED_HOSTS_BEGIN)


def _is_managed_block_end(stripped: str) -> bool:
    return stripped in (_MANAGED_HOSTS_END, _LEGACY_MANAGED_HOSTS_END)


def _parse_hosts_mapping_line(line: str) -> tuple[str, list[str], str] | None:
    mapping_part, sep, comment_part = str(line or "").partition("#")
    mapping_stripped = mapping_part.strip()
    if not mapping_stripped:
        return None

    parts = mapping_stripped.split()
    if len(parts) < 2:
        return None

    ip = parts[0]
    domains = parts[1:]
    comment = comment_part.strip() if sep else ""
    return ip, domains, comment


def _remove_managed_hosts_block(lines: list[str]) -> tuple[list[str], int]:
    """Удаляет управляемый блок из hosts и возвращает строки без него."""
    new_lines: list[str] = []
    removed_entries = 0
    inside_block = False

    for line in lines:
        stripped = line.strip()
        if _is_managed_block_begin(stripped):
            inside_block = True
            continue
        if inside_block:
            if stripped and not stripped.startswith("#"):
                removed_entries += 1
            if _is_managed_block_end(stripped):
                inside_block = False
            continue
        new_lines.append(line)

    return new_lines, removed_entries


def _format_hosts_mapping_line(ip: str, domains: list[str], comment: str) -> str:
    line = f"{ip} {' '.join(domains)}"
    if comment:
        line += f" # {comment}"
    return line + "\n"


def _format_hosts_entries_count(count: int) -> str:
    count = int(count)
    if count % 10 == 1 and count % 100 != 11:
        word = "запись"
    elif count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
        word = "записи"
    else:
        word = "записей"
    return f"{count} {word}"


def _iter_managed_hosts_block_rows(lines: list[str]) -> list[tuple[str, str]]:
    """Возвращает строки (domain, ip), которые лежат внутри блока net67."""
    rows: list[tuple[str, str]] = []
    inside_block = False

    for line in lines:
        stripped = line.strip()
        if _is_managed_block_begin(stripped):
            inside_block = True
            continue
        if not inside_block:
            continue
        if _is_managed_block_end(stripped):
            # Не break: блоков бывает больше одного. Пока BOM прятал маркер
            # первого блока, каждая запись ставила рядом новый, и на живых
            # машинах их находили по два. Удаление снимает все блоки сразу —
            # и сравнивать надо со всеми, иначе устаревший первый блок
            # выглядел бы «пустым» и обновление его пропускало.
            inside_block = False
            continue
        if not stripped or stripped.startswith("#"):
            continue

        parsed = _parse_hosts_mapping_line(stripped)
        if parsed is None:
            continue
        ip, domains, _comment = parsed
        for domain in domains:
            rows.append((domain, ip))

    return rows


def _insert_managed_hosts_block(new_lines: list[str], rows: list[tuple[str, str]], insert_at: int | None = None) -> None:
    """Добавляет управляемый блок перед обычными строками hosts."""
    if not rows:
        return

    if insert_at is None:
        insert_at = len(new_lines)
        for index, line in enumerate(new_lines):
            if _parse_hosts_mapping_line(line) is not None:
                insert_at = index
                break
    insert_at = max(0, min(insert_at, len(new_lines)))

    while insert_at > 0 and new_lines[insert_at - 1].strip() == "":
        del new_lines[insert_at - 1]
        insert_at -= 1
    while insert_at < len(new_lines) and new_lines[insert_at].strip() == "":
        del new_lines[insert_at]

    block: list[str] = []
    if insert_at > 0 and new_lines[insert_at - 1].strip() != "":
        block.append("\n")
    block.append(f"{_MANAGED_HOSTS_BEGIN}\n")
    block.append(f"{_MANAGED_HOSTS_NOTICE}\n")
    for domain, ip in rows:
        block.append(f"{ip} {domain}\n")
    block.append(f"{_MANAGED_HOSTS_END}\n")
    if insert_at < len(new_lines) and new_lines[insert_at].strip() != "":
        block.append("\n")

    new_lines[insert_at:insert_at] = block


# ───────────────────────── hosts file read cache ─────────────────────────
#
# На старте приложение может несколько раз читать hosts подряд (проверки/страницы UI).
# Файл маленький, но повторные чтения + перебор кодировок/обработка PermissionError
# могут давать заметную задержку. Делаем безопасный кэш "на процесс":
# - инвалидируем по сигнатуре файла (mtime_ns + size)
# - обновляем кэш после успешной записи

_HOSTS_TEXT_CACHE: str | None = None
_HOSTS_SIG_CACHE: tuple[int, int] | None = None  # (mtime_ns, size)


def _get_hosts_sig(path: Path) -> tuple[int, int] | None:
    try:
        st = path.stat()
        mtime_ns = getattr(st, "st_mtime_ns", None)
        if mtime_ns is None:
            mtime_ns = int(st.st_mtime * 1_000_000_000)
        return (int(mtime_ns), int(st.st_size))
    except Exception:
        return None


def _set_hosts_cache(content: str | None, sig: tuple[int, int] | None) -> None:
    global _HOSTS_TEXT_CACHE, _HOSTS_SIG_CACHE
    _HOSTS_TEXT_CACHE = content
    _HOSTS_SIG_CACHE = sig


def invalidate_hosts_file_cache() -> None:
    """Принудительно сбрасывает кэш чтения hosts (на случай внешних изменений)."""
    _set_hosts_cache(None, None)


def _run_cmd(args, description):
    """Выполняет команду и логирует результат"""
    try:
        result = subprocess.run(
            args,
            capture_output=True,
            text=True,
            creationflags=subprocess.CREATE_NO_WINDOW
        )
        if result.returncode == 0:
            log(f"✅ {description}: успешно")
            return True
        else:
            # Проверяем stderr или stdout на наличие ошибки
            error = result.stderr.strip() or result.stdout.strip()
            log(f"⚠ {description}: {error}", "⚠ WARNING")
            return False
    except Exception as e:
        log(f"❌ {description}: {e}", "❌ ERROR")
        return False


