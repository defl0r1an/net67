"""Провайдер как отправная точка подбора стратегии обхода.

У разных провайдеров разное оборудование фильтрации, и стратегия,
работающая на одном, на другом может не дать ничего. Отсюда и просьба
«под каждого провайдера свой конфиг».

Честная граница этого модуля: он даёт **подсказку, с чего начать**, а не
знание о том, что сработает. Настоящий ответ даёт только замер на живой
сети — «Подбор стратегии» в разделе диагностики.

Почему так, а не таблица «провайдер -> рабочий пресет»:

* В поставке 106 пресетов winws2, и только у одного в имени есть
  провайдер — «Ростелеком». Ни у одного нет поля с провайдером в
  метаданных. Взять соответствия неоткуда.
* Придумать таблицу из головы — ровно та ошибка, что уже стоила рабочего
  доступа: набор адресов «подмены DNS» тоже выглядел авторитетно, а на
  деле 44 домена вели на адреса сети.
* Фильтрация меняется от города к городу и от месяца к месяцу даже у
  одного провайдера. Таблица устареет раньше, чем разойдётся по машинам.

Поэтому: известный пресет — если он реально есть в поставке; иначе
стандартный, и сразу предложение измерить.
"""

from __future__ import annotations

from dataclasses import dataclass


#: Пресет по умолчанию. Он же остаётся, если про провайдера ничего не знаем.
DEFAULT_PRESET = "Стандартный 1.txt"

#: Ключ «не знаю» — им же помечается пропуск вопроса.
UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class Provider:
    """Провайдер в списке выбора.

    preset — имя файла пресета, с которого начинать. Пустая строка
    означает «специального нет, берём стандартный»: врать про наличие
    настройки под провайдера мы не будем.
    """

    key: str
    title: str
    preset: str = ""

    @property
    def has_special_preset(self) -> bool:
        return bool(self.preset)


#: Список для первого запуска. Порядок — по распространённости.
#:
#: Специальный пресет проставлен только там, где он есть в поставке
#: на самом деле. Проверяется тестом: файл обязан существовать.
PROVIDERS: tuple[Provider, ...] = (
    Provider("rostelecom", "Ростелеком", "Ростелеком.txt"),
    Provider("mts", "МТС"),
    Provider("beeline", "Билайн"),
    Provider("megafon", "МегаФон"),
    Provider("domru", "Дом.ру"),
    Provider("ttk", "ТТК"),
    Provider("tele2", "Tele2"),
    Provider("yota", "Yota"),
    Provider("other", "Другой провайдер"),
    Provider(UNKNOWN, "Не знаю"),
)

_BY_KEY: dict[str, Provider] = {item.key: item for item in PROVIDERS}


def get_provider(key: object) -> Provider:
    """Провайдер по ключу. Неизвестный ключ — «Не знаю»."""
    return _BY_KEY.get(str(key or "").strip().lower(), _BY_KEY[UNKNOWN])


def preset_for_provider(key: object) -> str:
    """С какого пресета начинать для этого провайдера."""
    provider = get_provider(key)
    return provider.preset or DEFAULT_PRESET


def needs_measurement(key: object) -> bool:
    """Нужно ли предложить подбор стратегии.

    Нужно всегда. Даже для Ростелекома пресет — только начальная точка:
    у него самого фильтрация в разных регионах разная. Функция оставлена
    отдельной, чтобы правило было видно и его нельзя было потерять при
    правке интерфейса.
    """
    _ = key
    return True


def describe_choice(key: object) -> str:
    """Что сказать человеку про его выбор. Без обещаний."""
    provider = get_provider(key)
    if provider.has_special_preset:
        return (
            f"Для «{provider.title}» есть отдельный набор настроек — начнём с него. "
            "Если что-то не откроется, точный подбор есть в разделе диагностики."
        )
    if provider.key == UNKNOWN:
        return (
            "Начнём со стандартных настроек. Какие подойдут именно вашей сети, "
            "покажет подбор стратегии в разделе диагностики."
        )
    return (
        f"Отдельных настроек под «{provider.title}» в поставке нет — начнём со "
        "стандартных. Подобрать точнее можно в разделе диагностики."
    )


