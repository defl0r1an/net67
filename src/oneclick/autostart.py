"""Каким показать состояние кнопки обхода сразу после её появления.

Настройка «Автозапуск обхода после старта программы» включает обход на
старте — этим занимается стартовый координатор, и в свёрнутом в трей
окне тоже (кнопки там ещё нет). Проблема была не в запуске, а в том, что
кнопка на главной этого не замечала: обход уже работал, а под кругом
висело «Обход выключен».

Кнопка создаётся лениво — при первом открытии главной страницы, — и к
этому моменту обход, включённый автозапуском, уже идёт. Поэтому первое,
что она делает, — сверяется с реальным состоянием рантайма и, если обход
работает, показывает это.

Модуль без Qt: здесь только решение, показывать «включено» или нет.
"""

from __future__ import annotations

from oneclick.state import OneClickState


def initial_button_state(*, bypass_running: bool) -> OneClickState:
    """Состояние кнопки при первом появлении.

    Обход уже работает (его включил автозапуск или прошлый сеанс) —
    показываем RUNNING. Иначе OFF: запускать отсюда ничего не нужно,
    старт — забота координатора и самой кнопки по нажатию.
    """
    return OneClickState.RUNNING if bool(bypass_running) else OneClickState.OFF


__all__ = ["initial_button_state"]
